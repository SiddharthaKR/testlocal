"""Generate broken variants of the reference FIR block into broken/.
Each must FAIL the medium judge (see judge_selftest.sh). Re-run after editing the reference."""
from pathlib import Path

HERE = Path(__file__).resolve().parent
REF = (HERE / "red_pitaya_fir_block.v").read_text()

SAT = "wire signed [14-1:0]  sat = (rnd >  8191) ? 14'sd8191  :\n                            (rnd < -8192) ? -14'sd8192 : rnd[14-1:0];"

VARIANTS = {
    # truncate instead of round half up
    "truncate": [("(acc + (1 <<< (COEF_FRAC-1))) >>> COEF_FRAC", "acc >>> COEF_FRAC")],
    # wrap instead of saturate
    "no_sat": [(SAT, "wire signed [14-1:0]  sat = rnd[14-1:0];")],
    # positive overflow clamps to the wrong polarity
    "sat_polarity": [("(rnd >  8191) ? 14'sd8191  :", "(rnd >  8191) ? -14'sd8192 :")],
    # tap order reversed (h0 applied to the oldest sample)
    "tap_order": [("p0 <= h0*xd0;", "p0 <= h0*xd7;"), ("p7 <= h7*xd7;", "p7 <= h7*xd0;"),
                  ("p1 <= h1*xd1;", "p1 <= h1*xd6;"), ("p6 <= h6*xd6;", "p6 <= h6*xd1;"),
                  ("p2 <= h2*xd2;", "p2 <= h2*xd5;"), ("p5 <= h5*xd5;", "p5 <= h5*xd2;"),
                  ("p3 <= h3*xd3;", "p3 <= h3*xd4;"), ("p4 <= h4*xd4;", "p4 <= h4*xd3;")],
    # off-by-one: h3 sees x[n-4]
    "tap3_off_by_one": [("p3 <= h3*xd3;", "p3 <= h3*xd4;")],
    # h7 stored in only 16 bits (writes truncated, sign-extended from bit 15)
    "h7_narrow": [("if (addr==16'h11C) h7 <= wdata[CB-1:0];", "if (addr==16'h11C) h7 <= {{2{wdata[15]}}, wdata[15:0]};")],
    # accumulator too narrow: sum of products overflows
    "acc_narrow": [("localparam ACC = 36;", "localparam ACC = 32;")],
    # last tap's product skips one pipeline stage (latency/alignment inconsistent across paths)
    "tap7_misaligned": [("s67 <= p6 + p7;", "s67 <= p6 + h7*xd6;")],
}

out = HERE / "broken"
out.mkdir(exist_ok=True)
for name, subs in VARIANTS.items():
    s = REF
    for old, new in subs:
        assert s.count(old) == 1, f"{name}: pattern not found once: {old!r}"
        s = s.replace(old, new)
    (out / f"{name}.v").write_text(f"// BROKEN VARIANT '{name}' (generated by make_broken.py)\n" + s)
    print(f"broken/{name}.v")
