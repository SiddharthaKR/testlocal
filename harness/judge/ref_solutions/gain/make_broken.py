"""Generate broken variants of the reference gain block into broken/.
Each must FAIL the easy judge (see judge_selftest.sh). Re-run after editing the reference."""
from pathlib import Path

HERE = Path(__file__).resolve().parent
REF = (HERE / "red_pitaya_gain_block.v").read_text()

VARIANTS = {
    # truncate instead of round half up
    "truncate": [("wire signed [32-1:0] sum  = p + half;", "wire signed [32-1:0] sum  = p;")],
    # wrap instead of saturate
    "no_sat": [("wire signed [14-1:0] sat  = (tot >  8191) ? 14'sd8191  :\n                            (tot < -8192) ? -14'sd8192 : tot[14-1:0];",
                "wire signed [14-1:0] sat  = tot[14-1:0];")],
    # positive overflow clamps to the wrong polarity
    "sat_polarity": [("(tot >  8191) ? 14'sd8191  :", "(tot >  8191) ? -14'sd8192 :")],
    # offset added before the shift
    "offset_before_shift": [("wire signed [32-1:0] sum  = p + half;", "wire signed [32-1:0] sum  = p + half + offset;"),
                            ("wire signed [32-1:0] tot  = rnd + offset;", "wire signed [32-1:0] tot  = rnd;")],
    # gain treated as unsigned
    "unsigned_gain": [("p   <= x0 * gain;", "p   <= x0 * $signed({1'b0, gain});")],
    # shift register only 3 bits wide (shift 8..15 broken)
    "shift_narrow": [("localparam SW = 4;", "localparam SW = 3;")],
    # latency differs for shift == 0 (output taken one register earlier)
    "latency_shift0": [("assign dat_o = out;", "assign dat_o = (shift == 0) ? sat : out;")],
}

out = HERE / "broken"
out.mkdir(exist_ok=True)
for name, subs in VARIANTS.items():
    s = REF
    for old, new in subs:
        assert s.count(old) == 1, f"{name}: pattern not found once: {old!r}"
        s = s.replace(old, new)
    (out / f"{name}.v").write_text(f"// BROKEN VARIANT '{name}' (generated by make_broken.py)\n" + s)
    print(f"broken/{name}.v")
