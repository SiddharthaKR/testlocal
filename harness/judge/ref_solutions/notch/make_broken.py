"""Generate broken variants of the reference notch block into broken/.
Each must FAIL the judge (see judge_selftest.sh). Re-run after editing the reference."""
from pathlib import Path

HERE = Path(__file__).resolve().parent
REF = (HERE / "red_pitaya_notch_block.v").read_text()

VARIANTS = {
    # truncate instead of round
    "truncate": [("(acc + (1 <<< (COEF_FRAC-1))) >>> COEF_FRAC", "acc >>> COEF_FRAC")],
    # feedback uses the unsaturated (wrapped-free, full-width) y; output still saturated
    "unsat_feedback": [
        ("reg signed [14-1:0] y1, y2;", "reg signed [14-1:0] y1, y2;\nreg signed [ACC-1:0] yf1, yf2;"),
        ("ff - a1*y1 - a2*y2", "ff - a1*yf1 - a2*yf2"),
        ("      y1 <= 0; y2 <= 0;", "      y1 <= 0; y2 <= 0; yf1 <= 0; yf2 <= 0;"),
        ("      y2 <= y1;", "      y2 <= y1;\n      yf1 <= rnd;\n      yf2 <= yf1;"),
    ],
    # wrong sign on a1
    "a1_sign": [("ff - a1*y1", "ff + a1*y1")],
    # coefficients stored in 16 bits (b1 near -2.0 no longer fits)
    "coef16": [("localparam CB  = 18;", "localparam CB  = 16;")],
    # bypass path one cycle shorter than the filter path
    "bypass_latency": [("assign dat_o = bypass ? x2 : y1;", "assign dat_o = bypass ? x1 : y1;")],
}

out = HERE / "broken"
out.mkdir(exist_ok=True)
for name, subs in VARIANTS.items():
    s = REF
    for old, new in subs:
        assert s.count(old) == 1, f"{name}: pattern not found once: {old!r}"
        s = s.replace(old, new)
    (out / f"{name}.v").write_text(f"// BROKEN VARIANT '{name}' (generated by make_broken.py)\n" + s)
    print(f"broken/{name}.v")
