# Sourced by harness scripts. Works in Git Bash (Windows) and Linux bash.
# Provides: ROOT, ENV_YAML, yaml_get, PYTHON, abspath, write_tool_env

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
ENV_YAML="${ENV_YAML:-$ROOT/config/env.yaml}"

# yaml_get <key>: scalar value of a top-level key (comments stripped)
yaml_get() { sed -n "s/^$1:[[:space:]]*\([^[:space:]#]*\).*/\1/p" "$ENV_YAML" | head -n1; }

# abspath <path>: resolve relative to ROOT
abspath() { case "$1" in /*|[A-Za-z]:*) echo "$1" ;; *) echo "$ROOT/$1" ;; esac; }

PYTHON="${PYTHON:-$(yaml_get python_cmd)}"
PYTHON="${PYTHON:-python3}"

# Native path for tools that are Windows executables (python, opencode); no-op on Linux.
nativepath() { if command -v cygpath >/dev/null 2>&1; then cygpath -m "$1"; else echo "$1"; fi; }

# write_tool_env <file>: config for agent tools that run inside workspace/
# (the agent never sees config/ or harness/).
write_tool_env() {
  local iv viv
  iv="$(yaml_get iverilog_dir)"; [ "$iv" = auto ] && iv=""
  viv="$(yaml_get vivado)"
  cat > "$1" <<EOF
# generated by harness from config/env.yaml — do not edit
PYTHON='$PYTHON'
IVERILOG_DIR='$iv'
VIVADO='$viv'
FPGA_PART='$(yaml_get fpga_part)'
CLK_PERIOD_NS='$(yaml_get clk_period_ns)'
EOF
}
